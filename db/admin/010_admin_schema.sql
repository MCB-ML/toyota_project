    c.company_info_id,
    c.company_info_name
   FROM (dbo."User_AD_master" a
     JOIN dbo."CompanyInfo_master" c ON ((c.company_info_id = a.default_company)))
  WHERE (a.is_active AND c.is_active AND (c.deleted_at IS NULL));


