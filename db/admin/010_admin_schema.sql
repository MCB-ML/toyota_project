-- =====================================================================
-- Ai365 Admin Center  |  PostgreSQL DDL  (dbo + agent 스키마)
-- =====================================================================
-- 스키마 2개를 같은 데이터베이스 안에 나눠 둔다.
--   dbo    어드민이 쓴다   - 딜러사 · 사용자 · 모델 · 프롬프트
--   agent  에이전트가 쓴다 - 대화 이력 · 토큰 사용량
--
-- 나누는 기준은 "누가 INSERT 하느냐"다. 읽기는 서로 자유롭게 한다.
--
-- 어드민 메뉴와 테이블
--   회사 정보     -> dbo."CompanyInfo_master"
--   사용자        -> dbo."User_master" / dbo."User_AD_master"
--   모델 배포     -> dbo."Model_master", dbo."CompanyInfo_ModelDeployment"
--   프롬프트 설정 -> dbo."SystemPrompt_Configuration"
--   사용량        -> agent."TokenUsage_log"
--
-- 딜러사(Company)는 단일 계층이다. Branch / Workspace 개념은 없고,
-- 활성/비활성은 CompanyInfo_master.is_active 로만 판단한다.
--
-- ※ 이 파일은 운영 중이던 로컬 DB 에서 pg_dump 로 복원한 것이다.
--   이전 버전(schema_postgres_core.sql / _agent.sql / _link.sql)은 인코딩이
--   깨지면서 컬럼 정의와 문자열 종료 따옴표가 사라져 빈 DB 에서 initdb 가
--   실패했다. 세 파일을 이 한 파일로 합쳐 대체한다.
--   딜러사 ↔ scope 연결 데이터는 050_admin_link.sql 이 이어서 채운다.
-- =====================================================================

