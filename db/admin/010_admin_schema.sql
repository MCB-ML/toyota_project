CREATE VIEW dbo.v_user_company AS
 SELECT u.user_id,
    lower((u.user_email)::text) AS user_email,
    u.user_name,
    u.user_role,
    u.user_department,
    u.default_language,
    'local'::character varying(10) AS provider,
    c.company_info_id,
    c.company_info_name
   FROM (dbo."User_master" u
     JOIN dbo."CompanyInfo_master" c ON ((c.company_info_id = u.default_company)))
  WHERE (u.is_active AND c.is_active AND (c.deleted_at IS NULL))
