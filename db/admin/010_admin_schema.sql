--
-- Name: v_token_usage_by_user; Type: VIEW; Schema: agent; Owner: -
--

CREATE VIEW agent.v_token_usage_by_user AS
 SELECT (t.created_at)::date AS usage_date,
    t.company_info_id,
    c.company_info_name,
    COALESCE(t.user_email, '(시스템)'::character varying) AS user_email,
    count(*) AS request_count,
    count(*) FILTER (WHERE (NOT t.succeeded)) AS failed_count,
    sum(t.input_tokens) AS input_tokens,
    sum(t.output_tokens) AS output_tokens,
    sum((t.input_tokens + t.output_tokens)) AS total_tokens,
    (avg(t.latency_ms))::integer AS avg_latency_ms,
    max(t.created_at) AS last_used_at
   FROM (agent."TokenUsage_log" t
     JOIN dbo."CompanyInfo_master" c ON ((c.company_info_id = t.company_info_id)))
  GROUP BY ((t.created_at)::date), t.company_info_id, c.company_info_name, COALESCE(t.user_email, '(시스템)'::character varying);


--
-- Name: VIEW v_token_usage_by_user; Type: COMMENT; Schema: agent; Owner: -
--

COMMENT ON VIEW agent.v_token_usage_by_user IS '날짜 x 딜러사 x 이메일 사용량. usage_date 로 기간을 거른 뒤 다시 합쳐 쓴다';


--
-- Name: v_token_usage_daily; Type: VIEW; Schema: agent; Owner: -
--

CREATE VIEW agent.v_token_usage_daily AS
 SELECT (t.created_at)::date AS usage_date,
    t.company_info_id,
    c.company_info_name,
    count(*) AS request_count,
    sum((t.input_tokens + t.output_tokens)) AS total_tokens
   FROM (agent."TokenUsage_log" t
     JOIN dbo."CompanyInfo_master" c ON ((c.company_info_id = t.company_info_id)))
  GROUP BY ((t.created_at)::date), t.company_info_id, c.company_info_name;


